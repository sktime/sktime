"""Tests for the LagLlama forecaster.

Covers golden-output regression against the source lag-llama package, and the
probabilistic interface: ``predict_proba`` returns an ``Empirical`` distribution
and ``predict_quantiles`` is consistent with it.
"""

# copyright: sktime developers, BSD-3-Clause License (see LICENSE file)

import numpy as np
import pytest

from sktime.datasets import load_airline
from sktime.forecasting.lagllama import LagLlamaForecaster
from sktime.tests.test_switch import run_test_for_class
from sktime.utils._testing.forecasting import make_forecasting_problem

# Reference forecasts were generated by calling lag_llama.gluon.estimator's
# LagLlamaEstimator directly (checkpoint "time-series-foundation-models/Lag-Llama",
# revision 72dcfc29da106acfe38250a60f4ae29d1e56a3d9)
_LAGLLAMA_REFERENCE_CASES = [
    pytest.param(
        {"context_length": 32, "num_samples": 100},
        [549.983642578, 524.926696777, 503.950927734],
        id="context32-samples100",
    ),
    pytest.param(
        {"context_length": 64, "num_samples": 100, "use_rope_scaling": True},
        [558.188964844, 544.520446777, 539.267822266],
        id="context64-rope-scaling",
    ),
    pytest.param(
        {"context_length": 32, "num_samples": 20, "nonnegative_pred_samples": True},
        [560.322875977, 557.898803711, 538.202148438],
        id="context32-samples20-nonnegative",
    ),
]


@pytest.mark.skipif(
    not run_test_for_class(LagLlamaForecaster),
    reason="run test only if softdeps are present and incrementally (if requested)",
)
@pytest.mark.parametrize(
    "forecaster_kwargs,expected_head",
    _LAGLLAMA_REFERENCE_CASES,
)
def test_lagllama_airline_predictions_match_source_reference(
    forecaster_kwargs, expected_head
):
    """LagLlama predictions match the original lag-llama package outputs."""
    y = load_airline()
    prediction_length = 16
    y_train = y.iloc[:-prediction_length]
    fh = np.arange(1, prediction_length + 1)
    forecaster = LagLlamaForecaster(
        **forecaster_kwargs,
        device="cpu",
    )

    y_pred = forecaster.fit(y_train, fh=fh).predict(fh=fh)

    np.testing.assert_allclose(
        y_pred.iloc[:3].to_numpy(),
        np.asarray(expected_head, dtype=np.float32),
        rtol=1e-5,
        atol=1e-4,
    )


@pytest.mark.skipif(
    not run_test_for_class(LagLlamaForecaster),
    reason="run test only if softdeps are present and incrementally (if requested)",
)
def test_lagllama_predict_proba_returns_empirical():
    """predict_proba returns an Empirical distribution over the horizon."""
    from skpro.distributions.empirical import Empirical

    params = LagLlamaForecaster.get_test_params("default")[0]
    forecaster = LagLlamaForecaster(**params)

    y = make_forecasting_problem(n_timepoints=50, random_state=42)
    forecaster.fit(y, fh=[1, 2, 3, 4, 5])

    pred_dist = forecaster.predict_proba()

    assert isinstance(pred_dist, Empirical)
    expected_index = forecaster.fh.to_absolute(forecaster.cutoff)
    assert pred_dist.index.equals(expected_index)
    assert len(pred_dist.columns) == 1


@pytest.mark.skipif(
    not run_test_for_class(LagLlamaForecaster),
    reason="run test only if softdeps are present and incrementally (if requested)",
)
def test_lagllama_predict_quantiles_consistency():
    """predict_quantiles agrees with predict_proba().quantile().

    Both derive from the same seeded Monte Carlo sample paths. predict_quantiles
    computes numpy percentiles (skpro-free), while predict_proba wraps the samples
    in an Empirical distribution; with enough samples the two quantile estimators
    converge, so their values must be close.
    """
    forecaster = LagLlamaForecaster(context_length=32, num_samples=100)

    y = load_airline()
    forecaster.fit(y, fh=[1, 2, 3, 4, 5])

    alpha = [0.1, 0.5, 0.9]
    quantiles_direct = forecaster.predict_quantiles(alpha=alpha)
    quantiles_from_proba = forecaster.predict_proba().quantile(alpha)

    np.testing.assert_allclose(
        quantiles_direct.to_numpy(),
        quantiles_from_proba.to_numpy(),
        rtol=0.1,
        atol=5.0,
    )


@pytest.mark.skipif(
    not run_test_for_class(LagLlamaForecaster),
    reason="run test only if softdeps are present and incrementally (if requested)",
)
def test_lagllama_predict_proba_panel():
    """predict_proba returns an Empirical distribution for panel data."""
    from skpro.distributions.empirical import Empirical

    from sktime.utils._testing.hierarchical import _make_hierarchical

    params = LagLlamaForecaster.get_test_params("default")[0]
    forecaster = LagLlamaForecaster(**params)

    y = _make_hierarchical(hierarchy_levels=(2,), min_timepoints=30, max_timepoints=30)
    forecaster.fit(y, fh=[1, 2, 3])

    pred_dist = forecaster.predict_proba()

    assert isinstance(pred_dist, Empirical)
    expected_index = forecaster.fh.to_absolute(forecaster.cutoff)
    assert pred_dist.index.equals(expected_index)
