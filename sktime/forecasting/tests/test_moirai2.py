"""Regression tests for the Moirai 2.0 forecaster."""

import numpy as np
import pandas as pd
import pytest
from skbase.utils.dependencies import _check_estimator_deps

from sktime.datasets import Longley, load_airline
from sktime.forecasting.moirai2 import Moirai2Forecaster


@pytest.mark.parametrize(
    "inferred_freq, expected",
    [
        ("YS-JAN", "Y"),
        ("AS-JAN", "Y"),
        ("QS-JAN", "Q"),
        ("QE-JAN", "Q-JAN"),
        ("QE-FEB", "Q-FEB"),
        ("QE-DEC", "Q"),
        ("YE-JAN", "Y-JAN"),
        ("AE-JAN", "Y-JAN"),
        ("YE-DEC", "Y"),
        ("AE-DEC", "Y"),
        ("YS-APR", "Y-MAR"),
        ("QS-FEB", "Q-JAN"),
        ("W-SUN", "W-SUN"),
        ("Q-DEC", "Q-DEC"),
    ],
)
def test_moirai2_infer_freq_anchored_aliases(inferred_freq, expected, monkeypatch):
    """Map inferred anchored date frequencies to valid period frequencies."""
    monkeypatch.setattr(pd, "infer_freq", lambda index: inferred_freq)
    forecaster = Moirai2Forecaster(checkpoint_path="Salesforce/moirai-2.0-R-small")

    assert forecaster.infer_freq(pd.date_range("2000-01-01", periods=3)) == expected


def test_moirai2_infer_freq_longley_datetime_index():
    """Longley's yearly DatetimeIndex converts to a GluonTS-compatible period."""
    df = Longley().load("y").to_timestamp().to_frame()
    forecaster = Moirai2Forecaster(checkpoint_path="Salesforce/moirai-2.0-R-small")

    freq = forecaster.infer_freq(df.index)

    assert freq == "Y"
    df.to_period(freq=freq)


def test_moirai2_infer_freq_quarterly_datetime_index():
    """A quarterly DatetimeIndex converts with the inferred period frequency."""
    df = pd.DataFrame(
        {"y": range(12)},
        index=pd.date_range("2000-01-01", periods=12, freq="QE-DEC"),
    )
    forecaster = Moirai2Forecaster(checkpoint_path="Salesforce/moirai-2.0-R-small")

    freq = forecaster.infer_freq(df.index)

    assert freq == "Q"
    df.to_period(freq=freq)


# Reference forecasts were generated by uni2ts's Moirai2Forecast/Moirai2Module,
# called directly (not through sktime), following the "Getting Started" example
# in the uni2ts README (https://github.com/SalesforceAIResearch/uni2ts).
_MOIRAI2_REFERENCE_CASES = [
    pytest.param(
        {"checkpoint_path": "Salesforce/moirai-2.0-R-small"},
        [
            474.166778564,
            396.643981934,
            348.568054199,
        ],
        id="default-context-length",
    ),
    pytest.param(
        {"checkpoint_path": "Salesforce/moirai-2.0-R-small", "context_length": 100},
        [
            467.202758789,
            400.953796387,
            362.836059570,
        ],
        id="context-length-100",
    ),
]


@pytest.mark.skipif(
    not _check_estimator_deps(Moirai2Forecaster, severity="none"),
    reason="run test only if Moirai2Forecaster soft dependencies are present",
)
@pytest.mark.parametrize(
    "forecaster_kwargs,expected_head",
    _MOIRAI2_REFERENCE_CASES,
)
def test_moirai2_airline_predictions_match_uni2ts_reference(
    forecaster_kwargs, expected_head
):
    """Moirai 2.0 predictions match the original uni2ts Moirai2Forecast pipeline."""
    y = load_airline()
    y_train = y.iloc[:-16]
    fh = np.arange(1, 17)
    forecaster = Moirai2Forecaster(use_source_package=False, **forecaster_kwargs)

    y_pred = forecaster.fit(y_train, fh=fh).predict(fh=fh)

    np.testing.assert_allclose(
        y_pred.iloc[:3].to_numpy(),
        np.asarray(expected_head, dtype=np.float32),
        rtol=1e-5,
        atol=1e-4,
    )
