"""Unit tests for all time series regressors."""

__author__ = ["mloning", "TonyBagnall", "fkiraly"]


import numpy as np
import pandas as pd
import pytest

from sktime.datatypes import check_is_scitype
from sktime.tests.test_all_estimators import BaseFixtureGenerator, QuickTester
from sktime.utils._testing.panel import make_regression_problem
from sktime.utils._testing.scenarios_classification import (
    ClassifierFitPredictMultivariate,
)
from sktime.utils.validation import is_float


class RegressorFixtureGenerator(BaseFixtureGenerator):
    """Fixture generator for classifier tests.

    Fixtures parameterized
    ----------------------
    object_class: estimator inheriting from BaseObject
        ranges over skbase classes not excluded by tests:skip_all/skip_by_name tags
    object_instance: instance of estimator inheriting from BaseObject
        ranges over skbase classes not excluded by tests:skip_all/skip_by_name tags
        instances are generated by create_test_instance class method
    scenario: instance of TestScenario
        ranges over all scenarios returned by retrieve_scenarios
    """

    # note: this should be separate from TestAllRegressors
    #   additional fixtures, parameters, etc should be added here
    #   TestAllRegressors should contain the tests only

    object_type_filter = "regressor"


class TestAllRegressors(RegressorFixtureGenerator, QuickTester):
    """Module level tests for all sktime regressors."""

    def test_multivariate_input_exception(self, object_instance):
        """Test univariate regressors raise exception on multivariate X."""
        # check if multivariate input raises error for univariate regressors

        # if handles multivariate, no error is to be raised
        #   that classifier works on multivariate data is tested in test_all_estimators
        if object_instance.get_tag("capability:multivariate"):
            return None

        error_msg = "multivariate series"

        # we can use the classifier scenario for multivariate regressors
        #   because the classifier scenario y is float
        scenario = ClassifierFitPredictMultivariate()

        # check if estimator raises appropriate error message
        #   composites will raise a warning, non-composites an exception
        if object_instance.is_composite():
            with pytest.warns(UserWarning, match=error_msg):
                scenario.run(object_instance, method_sequence=["fit"])
        else:
            with pytest.raises(ValueError, match=error_msg):
                scenario.run(object_instance, method_sequence=["fit"])

    def test_regressor_output(self, object_instance, scenario):
        """Test regressor outputs the correct data types and values.

        Test predict produces a np.array or pd.Series with only values seen in the train
        data, and that predict_proba probability estimates add up to one.
        """
        X_new = scenario.args["predict"]["X"]
        # we use check_is_scitype to get the number instances in X_new
        #   this is more robust against different scitypes in X_new
        _, _, X_new_metadata = check_is_scitype(X_new, "Panel", return_metadata=True)
        X_new_instances = X_new_metadata["n_instances"]

        # run fit and predict
        y_pred = scenario.run(object_instance, method_sequence=["fit", "predict"])
        # check score
        score = object_instance.score(X_new, y_pred)
        assert is_float(score)

        # check predict
        assert isinstance(y_pred, np.ndarray)
        assert y_pred.shape == (X_new_instances,)
        assert np.issubdtype(y_pred.dtype, np.floating)

    def test_multioutput(self, object_instance):
        """Test multioutput regression for all classifiers.

        All classifiers should follow the same interface,
        those that do not genuinely should vectorize/broadcast over y.
        """
        n_instances = 20
        X, y = make_regression_problem(n_instances=n_instances)
        y_mult = pd.DataFrame({"a": y, "b": y})

        object_instance.fit(X, y_mult)
        y_pred = object_instance.predict(X)
        # check score
        score = object_instance.score(X, y_mult)
        assert is_float(score)

        assert isinstance(y_pred, pd.DataFrame)
        assert y_pred.shape == y_mult.shape

        # the estimator vectorizes iff it does not have the multioutput capability
        vectorized = not object_instance.get_tag("capability:multioutput")
        if vectorized:
            assert hasattr(object_instance, "regressors_")
            assert isinstance(object_instance.regressors_, pd.DataFrame)
            assert object_instance.regressors_.shape == (1, 2)

    def test_pretrain_capability_tag(self, object_instance):
        """Test that regressors with capability:pretrain implement _pretrain.

        The converse is not checked, since composites may override ``_pretrain``,
        and set the tag depending on their components.
        """
        from sktime.regression.base import BaseRegressor

        can_pretrain = object_instance.get_tag(
            "capability:pretrain", tag_value_default=False, raise_error=False
        )
        if not can_pretrain:
            return None

        has_custom_pretrain = (
            type(object_instance)._pretrain is not BaseRegressor._pretrain
        )
        assert has_custom_pretrain, (
            f"{type(object_instance).__name__} has the tag "
            "capability:pretrain=True but does not override _pretrain"
        )

    @pytest.mark.parametrize("pass_y", [False, True], ids=["y_none", "y_targets"])
    def test_pretrain_is_noop(self, object_instance, pass_y):
        """Test pretrain is callable, and stores nothing without the capability.

        Estimators with the capability are tested in the workflow test, as they
        may require y in pretrain, e.g., if not capable of self-supervision.
        """
        if object_instance.get_tag(
            "capability:pretrain", tag_value_default=False, raise_error=False
        ):
            return None

        X, y = make_regression_problem()
        estimator = object_instance
        attrs_before = dict(vars(estimator))

        result = estimator.pretrain(X, y=y if pass_y else None)

        assert result is estimator
        assert estimator.state == "pretrained"
        assert not estimator.is_fitted
        assert estimator.get_pretrained_params() == {}
        # nothing is stored, only the state changes
        assert vars(estimator).keys() == attrs_before.keys()
        unchanged = {k: v for k, v in attrs_before.items() if k != "_state"}
        assert all(vars(estimator)[k] is v for k, v in unchanged.items())

    def test_pretrain_fit_predict_workflow(self, object_instance):
        """Test pretrain, fit, refit, and pretrain after fit.

        For regressors with capability:pretrain, checks the state transitions,
        and that pretrained parameters are retained by fit, refit, clone,
        and pretrain after fit, while pretrain after fit discards fitted state.
        """
        from sktime.exceptions import NotFittedError

        if not object_instance.get_tag(
            "capability:pretrain", tag_value_default=False, raise_error=False
        ):
            return None

        estimator = object_instance
        X_pretrain, y_pretrain = make_regression_problem(random_state=0)
        X, y = make_regression_problem(random_state=1)

        estimator.pretrain(X_pretrain, y_pretrain)
        assert estimator.state == "pretrained"
        assert not estimator.is_fitted
        pretrained = set(estimator.get_pretrained_params(deep=False))

        # pretrain on a pretrained regressor calls _pretrain_update
        estimator.pretrain(X_pretrain, y_pretrain)
        assert estimator.state == "pretrained"
        assert pretrained <= set(estimator.get_pretrained_params(deep=False))

        estimator.fit(X, y)
        assert estimator.state == "fitted"
        assert pretrained <= set(estimator.get_pretrained_params(deep=False))
        # keys of get_fitted_params are attribute names without the trailing "_"
        fitted = set(estimator.get_fitted_params(deep=False))
        assert {attr[:-1] for attr in pretrained}.isdisjoint(fitted)
        y_pred = estimator.predict(X)
        assert len(y_pred) == len(y)

        # refit retains the pretrained state
        estimator.fit(X, y)
        assert estimator.state == "fitted"
        assert pretrained <= set(estimator.get_pretrained_params(deep=False))

        # clone retains the pretrained state, but not the fitted state
        cloned = estimator.clone()
        assert cloned.state == "pretrained"
        assert pretrained <= set(cloned.get_pretrained_params(deep=False))

        # pretrain after fit discards the fitted state,
        # and retains the pretrained state
        estimator.pretrain(X_pretrain, y_pretrain)
        assert estimator.state == "pretrained"
        assert not estimator.is_fitted
        assert pretrained <= set(estimator.get_pretrained_params(deep=False))
        with pytest.raises(NotFittedError):
            estimator.predict(X)
