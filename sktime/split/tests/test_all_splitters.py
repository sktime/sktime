"""Unit tests for time series splitters."""

__author__ = ["fkiraly"]

import types

import numpy as np
import pandas as pd
import pytest

from sktime.tests.test_all_estimators import BaseFixtureGenerator, QuickTester
from sktime.utils._testing.hierarchical import _make_hierarchical
from sktime.utils._testing.series import _make_series


class SplitterFixtureGenerator(BaseFixtureGenerator):
    """Fixture generator for splitter tests.

    Fixtures parameterized
    ----------------------
    object_class: estimator inheriting from BaseObject
        ranges over skbase classes not excluded by tests:skip_all/skip_by_name tags
    object_instance: instance of estimator inheriting from BaseObject
        ranges over skbase classes not excluded by tests:skip_all/skip_by_name tags
        instances are generated by create_test_instance class method
    """

    # note: this should be separate from TestAllSplitters
    #   additional fixtures, parameters, etc should be added here
    #   TestAllSplitters should contain the tests only

    object_type_filter = "splitter"


class TestAllSplitters(SplitterFixtureGenerator, QuickTester):
    """Module level tests for all sktime time series splitters."""

    @pytest.mark.parametrize("hierarchical", [False, True])
    def test_split(self, object_instance, hierarchical):
        """Test contract for split."""
        splitter = object_instance

        if hierarchical:
            y = _make_hierarchical()
        else:
            y = _make_series()
            # instance splitters do not support single series
            # and should raise informative error message instead
            if splitter.get_tag("split_type") == "instance":
                with pytest.raises(ValueError, match="requires Panel"):
                    list(splitter.split(y))
                return None

        n_splits = splitter.get_n_splits(y)

        assert isinstance(n_splits, int)

        gen_split = splitter.split(y)

        assert isinstance(gen_split, types.GeneratorType)

        splits = list(gen_split)

        assert isinstance(splits, list)

        assert len(splits) == n_splits
        for x in splits:
            arity = splitter.get_tag("split:arity")
            folds = (x,) if arity == 1 else x
            assert isinstance(folds, tuple)
            assert len(folds) == arity
            for fold in folds:
                assert isinstance(fold, np.ndarray)
                assert fold.ndim == 1
                assert fold.dtype in [np.int64, np.int32]
                assert np.all(fold >= 0)
                assert np.all(fold < len(y))

    @pytest.mark.parametrize("hierarchical", [False, True])
    def test_split_loc(self, object_instance, hierarchical):
        """Test contract for split_loc."""
        splitter = object_instance

        if hierarchical:
            y = _make_hierarchical()
        else:
            y = _make_series()
            # instance splitters do not support single series
            # and should raise informative error message instead
            if splitter.get_tag("split_type") == "instance":
                with pytest.raises(ValueError, match="requires Panel"):
                    list(splitter.split(y))
                return None

        n_splits = splitter.get_n_splits(y)

        assert isinstance(n_splits, int)

        gen_split = splitter.split_loc(y)

        assert isinstance(gen_split, types.GeneratorType)

        splits = list(gen_split)

        assert isinstance(splits, list)
        assert len(splits) == n_splits

        for x in splits:
            arity = splitter.get_tag("split:arity")
            folds = (x,) if arity == 1 else x
            assert isinstance(folds, tuple)
            assert len(folds) == arity
